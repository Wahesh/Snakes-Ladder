export const nepaliDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

export function toNepaliNumber(num: number): string {
  return num
    .toString()
    .split('')
    .map((d) => {
      const idx = parseInt(d, 10);
      return isNaN(idx) ? d : nepaliDigits[idx];
    })
    .join('');
}

